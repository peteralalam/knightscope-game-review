// Build lib/opening-book-data.ts from a checkout of
// https://github.com/lichess-org/chess-openings (CC0 1.0).
//
//   git clone --depth 1 https://github.com/lichess-org/chess-openings.git /tmp/chess-openings
//   node scripts/build-opening-book.mjs /tmp/chess-openings
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { Chess } from "chess.js";
import { positionKey } from "../lib/opening-book.ts";

const source = process.argv[2];
if (!source) {
  console.error("usage: node scripts/build-opening-book.mjs <chess-openings checkout>");
  process.exit(1);
}

let commit = "unknown";
try {
  commit = execFileSync("git", ["-C", source, "rev-parse", "HEAD"], { encoding: "utf8" }).trim();
} catch {
  // Not a git checkout; keep "unknown".
}

const keys = new Set();
let lines = 0;
for (const file of ["a.tsv", "b.tsv", "c.tsv", "d.tsv", "e.tsv"]) {
  const rows = readFileSync(join(source, file), "utf8").trim().split("\n").slice(1);
  for (const row of rows) {
    const pgn = row.split("\t")[2];
    const chess = new Chess();
    chess.loadPgn(pgn);
    const replay = new Chess();
    for (const move of chess.history()) {
      replay.move(move);
      keys.add(positionKey(replay.fen()));
    }
    lines += 1;
  }
}

const data = [...keys].sort().join("");
writeFileSync(
  new URL("../lib/opening-book-data.ts", import.meta.url),
  `// Generated by scripts/build-opening-book.mjs – do not edit by hand.\n` +
    `// Source: lichess-org/chess-openings@${commit} (CC0 1.0), ${lines} named lines, ${keys.size} positions.\n` +
    `export const OPENING_BOOK_SOURCE = ${JSON.stringify(`lichess-org/chess-openings@${commit.slice(0, 12)}`)};\n` +
    `export const OPENING_BOOK_DATA =\n  ${JSON.stringify(data)};\n`,
);
console.log(`${lines} lines → ${keys.size} positions`);
